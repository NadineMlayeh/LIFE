/**
 * Every country you can pin to the wall map: ISO 3166-1 alpha-2 code, name, the region it is
 * filed under, and an approximate centroid in degrees.
 *
 * The centroids are eyeballed to a degree or two, deliberately. This is a decorative wall map
 * read from across a room, not an atlas, and hand-kept numbers mean no dataset dependency and
 * no build step. Small island states are placed where a pin will actually be legible rather
 * than at their true centre.
 */
export type Region = 'Africa' | 'Americas' | 'Asia' | 'Europe' | 'Oceania'

export interface CountryRef {
  /** ISO 3166-1 alpha-2. The key everything else is stored against. */
  code: string
  name: string
  region: Region
  /** Degrees: longitude -180..180, latitude -90..90. */
  lon: number
  lat: number
}

